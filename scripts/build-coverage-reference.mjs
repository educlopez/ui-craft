#!/usr/bin/env node
/**
 * build-coverage-reference.mjs
 * Generates skills/ui-craft/references/coverage.md from mcp/src/coverage-data.mjs.
 *
 * Why generated rather than hand-written: the coverage parts have to exist in two
 * places — the MCP tool serves them to callers that have the server, and the
 * reference file serves the installs that do not. Maintaining both by hand means
 * one of them goes stale, and the stale one is the fallback, so the failure only
 * shows up for the users with the least tooling. One source, one generator.
 *
 * Output is deliberately byte-stable: no generation date, no counts that shift for
 * reasons other than content. A file that changes on every run turns the drift
 * check below into noise, and a noisy check gets ignored.
 *
 *   node scripts/build-coverage-reference.mjs           # write
 *   node scripts/build-coverage-reference.mjs --check   # fail if out of date
 *
 * After writing, run `npm run sync` to push the file into the harness mirrors.
 */

import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'skills', 'ui-craft', 'references', 'coverage.md');
const SOURCE = 'mcp/src/coverage-data.mjs';

const { default: coverageData } = await import(join(ROOT, 'mcp', 'src', 'coverage-data.mjs'));

const FAMILY_LABELS = {
  'web-app': 'Web app',
  website: 'Website',
  flows: 'Flows',
};

function render(data) {
  const archetypes = Object.entries(data.archetypes);
  const byFamily = new Map();
  for (const [key, entry] of archetypes) {
    if (!byFamily.has(entry.family)) byFamily.set(entry.family, []);
    byFamily.get(entry.family).push([key, entry]);
  }

  const lines = [
    '# UX Coverage — the parts a screen needs',
    '',
    `**Generated from \`${SOURCE}\`. Do not edit this file — edit the data module and run \`node scripts/build-coverage-reference.mjs\`.**`,
    '',
    'This is the **completeness** axis. It asks whether a screen has the parts screens of',
    'its kind need. It is not the distinction axis — [finish-bar.md](finish-bar.md), the',
    'surface recipes and `check_anti_slop` answer *is this designed*. Report the two side',
    'by side.',
    '',
    'If the MCP server is connected, call `ux_coverage` instead of reading this file — it',
    'returns one archetype rather than all of them, and carries the reporting contract with',
    'it. This file is the fallback for installs without the server.',
    '',
    '## Reporting contract',
    '',
    'Each part gets one marker:',
    '',
    '| Marker | Meaning |',
    '|---|---|',
    '| **present** | the part is there, doing what it describes |',
    '| **partial** | there but incomplete or weakened — say which half is missing |',
    '| **missing** | not there, and it should be — say what it costs the user |',
    '| **not-needed** | absent and that is correct here — needs a stated reason, not just an absence you would rather not flag |',
    '| **unknown** | what you were given does not show enough to tell — say whether more input would settle it |',
    '',
    '**No score, no count, no percentage.** "6 of 8" makes `not-needed` read as a failure and',
    'turns a review into a grade. It also re-creates the problem `score_ui` already has:',
    'coverage is a hygiene axis, and hygiene axes tie at the top, so a coverage number would',
    'read 100 for most surfaces while hiding the distinction signal underneath it.',
    '',
    '**Coverage never gates.** It does not fail a build and does not exit non-zero.',
    '',
    '`not-needed` requires a reason. If you cannot say why a part does not apply here, it is',
    'missing. And do not invent presence — if you cannot see it, you cannot confirm it,',
    'however likely it is to exist somewhere.',
    '',
    '## What is not here',
    '',
    '**Dashboard, landing and auth** have full outcome recipes with their own acceptance bars',
    '([recipe-dashboard.md](recipe-dashboard.md), [recipe-landing.md](recipe-landing.md),',
    '[recipe-auth.md](recipe-auth.md)) — use those. Two homes for one requirement is how one',
    'of them goes stale.',
    '',
    '**States** are not restated here. [state-design.md](state-design.md) owns the lattice',
    '(idle / loading / empty / error / partial / success / conflict / offline) and the',
    '`state-coverage` loop preset evaluates it. Each archetype below names only the lattice',
    'instances that are non-obvious *for that archetype* — a data table\'s filtered-empty is a',
    'different screen from its first-run-empty, and that is archetype knowledge, not lattice',
    'knowledge.',
    '',
    'An archetype that is not listed is not a failure. Coverage is deliberately partial —',
    'review the surface without a coverage pass.',
    '',
    '## Archetypes',
    '',
  ];

  for (const [family, entries] of byFamily) {
    lines.push(`### ${FAMILY_LABELS[family] ?? family}`, '');
    for (const [key, entry] of entries) {
      lines.push(`- [${entry.label}](#${key}) \`${key}\` — ${entry.also.slice(0, 4).join(', ')}`);
    }
    lines.push('');
  }

  lines.push('---', '');

  for (const [key, entry] of archetypes) {
    lines.push(`## ${key}`, '', `**${entry.label}** · ${FAMILY_LABELS[entry.family] ?? entry.family}`, '');
    lines.push(`Also called: ${entry.also.join(', ')}.`, '');

    lines.push('**Non-obvious states for this archetype** (lattice in [state-design.md](state-design.md)):', '');
    for (const state of entry.states) lines.push(`- ${state}`);
    lines.push('');

    for (const item of entry.items) {
      lines.push(`### ${item.part}`, '');
      lines.push(`_${item.category}_`, '');
      lines.push(`**Present looks like:** ${item.exists}`, '');
      if (item.craft !== '—') lines.push(`**How to build it:** ${item.craft}`, '');
      lines.push(`**Cost if absent:** ${item.cost}`, '');
    }

    lines.push('---', '');
  }

  lines.push(
    '## Cross-refs',
    '',
    '[state-design.md](state-design.md) state lattice · [forms.md](forms.md) validation, multi-step, autosave ·',
    '[components.md](components.md) buttons, menus, modals, search, destructive ladder ·',
    '[dashboard.md](dashboard.md) tables, toolbars, signal-to-noise ·',
    '[finish-bar.md](finish-bar.md) the distinction axis this is reported beside',
    ''
  );

  return `${lines.join('\n').replace(/\n{3,}/g, '\n\n').trimEnd()}\n`;
}

const rendered = render(coverageData);
const check = process.argv.includes('--check');

if (check) {
  let current = null;
  try {
    current = await readFile(OUT, 'utf8');
  } catch {
    console.error(`✖ ${OUT} does not exist. Run: node scripts/build-coverage-reference.mjs`);
    process.exit(1);
  }
  if (current !== rendered) {
    console.error(
      `✖ references/coverage.md is out of date with ${SOURCE}.\n` +
        '  Run: node scripts/build-coverage-reference.mjs && npm run sync'
    );
    process.exit(1);
  }
  console.log('✓ references/coverage.md is in sync with coverage-data.mjs');
} else {
  await writeFile(OUT, rendered);
  const count = Object.values(coverageData.archetypes).reduce((n, a) => n + a.items.length, 0);
  console.log(
    `✓ references/coverage.md — ${Object.keys(coverageData.archetypes).length} archetypes, ${count} parts\n` +
      '  Run `npm run sync` to push it into the harness mirrors.'
  );
}
